        guard AppLocalization.language == .simplifiedChinese else { return label }
        if label == "Maximum Capacity", value?.contains("%") == true { return "最大容量（健康度）" }
        if let translated = extra[label] ?? chinese[label] { return translated }
        if label.hasPrefix("Thunderbolt/USB4 Bus ") { return label.replacingOccurrences(of: "Thunderbolt/USB4 Bus ", with: "雷雳 / USB4 总线 ") }
        if label.hasSuffix(" Bus"), label.hasPrefix("USB ") { return String(label.dropLast(4)) + " 总线" }
        return label
    }

